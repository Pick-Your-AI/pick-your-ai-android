        val bytes = ("""{"x_t0_answer_states":{"proposal_version":"cd1-0.2","answers":""" +
            """{"/f":{"state":"provided","value":$value,"assumption":false}}}}""").toByteArray()
        return try {
            Cd1AnswerIndex.read(bytes).read("/f", KnownAnswerSchema.read(schema.toByteArray())).provided
        } catch (rejected: Cd1Rejected) {
            if (rejected.problem == Cd1Problem.VALUE_SCHEMA_MISMATCH) false else throw rejected
        }
    }

